#!/usr/bin/env node
// Collects everything the agent needs to start a /heredia-front-audit run and prints it as Markdown:
// run directory, branch, uncommitted changes (staged + unstaged + untracked) and how to start the app (any stack).
// Always exits 0 so it never aborts the skill.
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync, existsSync, readFileSync, readdirSync } from "node:fs";
import { join, dirname, relative, sep } from "node:path";
import { detectStack, summarizeChangedFiles } from "./detect-stack.mjs";

const MAX_DIFF_LINES = Number(process.env.HEREDIA_FRONT_AUDIT_MAX_DIFF_LINES || 2500);
// Paths that belong to tooling, not to the app under test.
const IGNORED = [".heredia-front-audit/", ".claude/", ".agents/", ".codex/"];

const sh = (cmd) => {
  try {
    return execSync(cmd, { stdio: ["ignore", "pipe", "ignore"], maxBuffer: 64 * 1024 * 1024 }).toString();
  } catch {
    return null;
  }
};
const keep = (path) => !IGNORED.some((p) => path.startsWith(p));
const out = [];
const section = (title, body) => out.push(`### ${title}\n\n${body}\n`);
const fence = (s) => "```\n" + (s?.trimEnd() || "(empty)") + "\n```";

// ---- repo + run dir ----
const root = sh("git rev-parse --show-toplevel")?.trim() || process.cwd();
const isGit = sh("git rev-parse --is-inside-work-tree")?.trim() === "true";
const base = join(root, ".heredia-front-audit");
const d = new Date();
const p2 = (n) => String(n).padStart(2, "0");
const stamp = `${d.getFullYear()}-${p2(d.getMonth() + 1)}-${p2(d.getDate())}_${p2(d.getHours())}-${p2(d.getMinutes())}-${p2(d.getSeconds())}`;
const runDir = join(base, "runs", stamp);
mkdirSync(join(runDir, "screenshots"), { recursive: true });
if (!existsSync(join(base, ".gitignore"))) writeFileSync(join(base, ".gitignore"), "# generated by heredia-front-audit\n*\n");

section("Run directory (write everything here)", fence(runDir));

// No git or no changes doesn't end the run: a flow the user described can still be audited.
const statusLines = isGit ? gitSections() : [];
if (!isGit) {
  section("Git", "NOT A GIT REPOSITORY — there is no diff. Audit the flow the user described; if they described none, ask them which flow to audit.");
}

function gitSections() {
const hasHead = sh("git rev-parse --verify HEAD") !== null;
const branch = sh("git rev-parse --abbrev-ref HEAD")?.trim() || "(unknown)";
const sha = hasHead ? sh("git rev-parse --short HEAD")?.trim() : "(no commits yet)";
section("Repository", `- root: \`${root}\`\n- branch: \`${branch}\`\n- HEAD: \`${sha}\``);

// ---- status ----
const statusLines = (sh("git status --porcelain=v1 --untracked-files=all") || "")
  .split("\n").filter(Boolean).filter((l) => keep(l.slice(3)));
if (!statusLines.length) {
  section("Working tree", "NO UNCOMMITTED CHANGES — audit the flow the user described; if they described none, ask them which flow to audit.");
  return statusLines;
}
section("Working tree status (XY path; ?? = untracked)", fence(statusLines.join("\n")));

const untracked = statusLines.filter((l) => l.startsWith("??")).map((l) => l.slice(3));
if (untracked.length) {
  section("Untracked files — not in the diff below, read each one in full", untracked.map((f) => `- ${f}`).join("\n"));
}

// ---- diff ----
const pathspec = `-- . ${IGNORED.map((p) => `":(exclude)${p}"`).join(" ")}`;
const statCmd = hasHead ? `git diff HEAD --stat ${pathspec}` : `git diff --cached --stat ${pathspec}`;
const diffCmd = hasHead ? `git diff HEAD ${pathspec}` : `git diff --cached ${pathspec}`;
section("Diff stats vs HEAD (staged + unstaged)", fence(sh(statCmd)));

const diff = (sh(diffCmd) || "").split("\n");
let diffText = diff.slice(0, MAX_DIFF_LINES).join("\n");
if (diff.length > MAX_DIFF_LINES) {
  diffText += `\n\n[diff truncated at ${MAX_DIFF_LINES} of ${diff.length} lines — run \`git diff HEAD -- <file>\` for the files not shown]`;
}
section("Full diff vs HEAD", "```diff\n" + (diffText.trimEnd() || "(no tracked-file changes; see untracked files)") + "\n```");
return statusLines;
}

// ---- stack detection (framework-agnostic) ----
// In a monolith or monorepo the app may live in a sub-folder (frontend/, web/, apps/x/): use the
// nearest folder above each changed file that has a project manifest, plus the repo root.
const changedPaths = statusLines.map((l) => l.slice(3).replace(/^"|"$/g, "").split(" -> ").pop());
const MARKERS = ["package.json", "composer.json", "artisan", "angular.json", "Gemfile", "manage.py", "pyproject.toml",
  "wp-config.php", "docker-compose.yml", "compose.yml", ".ddev", "go.mod", "pom.xml"];
const appDirFor = (file) => {
  for (let d = dirname(file); d !== "." && d !== "/" && d !== ""; d = dirname(d)) {
    if (MARKERS.some((m) => existsSync(join(root, d, m)))) return d;
  }
  return ".";
};
const cwdRel = relative(root, process.cwd()).split(sep).join("/") || ".";
const appDirs = [...new Set([...changedPaths.map(appDirFor), cwdRel, "."])]
  .filter((d) => d === "." || !d.startsWith(".."));

const notes = new Set();
let anyUrl = false;
for (const d of appDirs) {
  const stack = detectStack([join(root, d)]);
  if (d !== "." && !stack.stacks.length && !stack.start.length) continue;
  stack.notes.forEach((n) => notes.add(n));
  anyUrl ||= stack.urls.length > 0;
  section(`Project stack in \`${d === "." ? "(repo root)" : d + "/"}\` (auto-detected — verify before relying on it)`, [
    `- stack: ${stack.stacks.join(", ") || "(unknown — inspect the repo)"}`,
    `- manifests: ${stack.manifests.map((m) => `\`${m}\``).join(", ") || "(none)"}`,
    `- changed files here: ${changedPaths.filter((p) => appDirFor(p) === d).length}`,
    "- likely app URLs:",
    ...(stack.urls.length ? stack.urls.map((u) => `  - ${u}`) : ["  - (none inferred)"]),
    `- ways to start it${d === "." ? "" : ` (run them inside \`${d}/\`)`}:`,
    ...(stack.start.length ? stack.start.map((c) => `  - \`${c}\``) : ["  - (none inferred)"]),
  ].join("\n"));
}
section("Changed files and notes", [
  `- changed file kinds: ${summarizeChangedFiles(changedPaths) || "(none)"}`,
  ...(appDirs.length > 1 ? ["- several project folders were found: test the one(s) the changed files belong to."] : []),
  ...[...notes].filter((n) => !(anyUrl && n.startsWith("No dev URL"))).map((n) => `- note: ${n}`),
].join("\n"));

// ---- URL from the previous run (saves the user from passing it every time) ----
const lastUrl = readdirSync(join(base, "runs")).sort().reverse().map((r) => {
  try { return JSON.parse(readFileSync(join(base, "runs", r, "findings.json"), "utf8")).baseUrl; } catch { return null; }
}).find(Boolean);
if (lastUrl) section("App URL from the previous run — try it first", fence(lastUrl));

const pkgFile = join(root, "package.json");
if (existsSync(pkgFile)) {
  try {
    const pkg = JSON.parse(readFileSync(pkgFile, "utf8"));
    section("package.json scripts", fence(JSON.stringify(pkg.scripts ?? {}, null, 2)));
  } catch {}
}
const composerFile = join(root, "composer.json");
if (existsSync(composerFile)) {
  try {
    const c = JSON.parse(readFileSync(composerFile, "utf8"));
    if (c.scripts) section("composer.json scripts", fence(JSON.stringify(c.scripts, null, 2)));
  } catch {}
}

console.log(out.join("\n"));
